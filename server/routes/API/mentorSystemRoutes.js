const router = require('../../utils/asyncRouter')();
const { protect } = require('../../middleware/authMiddleware');
const { rejectOwnerFields, scopeError } = require('../../services/coreScopeService');
const core = require('../../services/coreContextService');
const compat = require('../../services/mentorCompatibilityService');
router.use(protect);
router.use((req,_res,next)=>{try{rejectOwnerFields(req.body || {});next();}catch(error){next(error);}});
router.post('/intake',async(req,res)=>res.json({status:'MENTOR_INTAKE_SAVED',data:await compat.saveIntake(req.body)}));
router.get('/intake',async(_req,res)=>res.json(await compat.getIntake()));
router.post('/signals',async(req,res)=>res.status(201).json(await compat.signal(req.body)));
router.get('/signals',async(req,res)=>res.json(await compat.signals(req.query.signal_type)));
router.post('/tasks',async(req,res)=>res.status(201).json(await compat.createTask(req.body)));
router.get('/tasks',async(req,res)=>res.json(await compat.tasks(req.query.status)));
router.post('/messages',async(req,res)=>res.status(201).json(await compat.message(req.body)));
router.get('/messages',async(_req,res)=>res.json(await compat.messages()));
router.post('/protocols',async(req,res)=>res.status(201).json(await core.createProtocol(req.body)));
router.get('/protocols',async(_req,res)=>res.json(await core.listProtocols()));
router.post('/user-protocols',async(req,res)=>res.json(await core.saveUserProtocol(req.body)));
router.get('/user-protocols',async(_req,res)=>res.json(await core.listUserProtocols()));
router.post('/loop-status',()=>{throw scopeError('Loop status is server-owned. Use authenticated operator controls.',409);});
router.get('/loop-status',async(_req,res)=>res.json(await core.loopStatus()));
module.exports=router;
